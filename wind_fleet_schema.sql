-- =============================================================================
-- Renewable Wind Turbine Fleet Predictive Maintenance Engine
-- Database Schema: wind_fleet_db
-- Target: MySQL 8.0+ Enterprise / Community Server
-- Architecture: 2-Tier Architecture (VM 1 App Host / VM 2 DB Host)
-- =============================================================================

CREATE DATABASE IF NOT EXISTS wind_fleet_db
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE wind_fleet_db;

-- Drop dependent tables first
DROP TABLE IF EXISTS downtime_logs;
DROP TABLE IF EXISTS maintenance_tickets;
DROP TABLE IF EXISTS scada_telemetry;
DROP TABLE IF EXISTS turbines;

-- -----------------------------------------------------------------------------
-- 1. TURBINES TABLE: Master registry of wind turbine assets across farm sectors
-- -----------------------------------------------------------------------------
CREATE TABLE turbines (
    turbine_id VARCHAR(30) NOT NULL,
    farm_sector VARCHAR(50) NOT NULL,
    category VARCHAR(50) NOT NULL,
    max_rated_capacity_mw DECIMAL(6, 2) NOT NULL,
    max_gearbox_temp_cap DECIMAL(5, 2) NOT NULL,
    commission_date DATE NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_turbines PRIMARY KEY (turbine_id),
    CONSTRAINT chk_turbine_category CHECK (category IN (
        'OFFSHORE DEEPWATER TURBINE',
        'ONSHORE DESERT TURBINE',
        'HIGH-ALTITUDE MOUNTAIN TURBINE'
    )),
    CONSTRAINT chk_capacity CHECK (max_rated_capacity_mw > 0),
    CONSTRAINT chk_temp_cap CHECK (max_gearbox_temp_cap > 0)
) ENGINE=InnoDB;

-- -----------------------------------------------------------------------------
-- 2. SCADA_TELEMETRY TABLE: Time-series operational telemetry stream from sensors
-- -----------------------------------------------------------------------------
CREATE TABLE scada_telemetry (
    telemetry_id BIGINT AUTO_INCREMENT NOT NULL,
    turbine_id VARCHAR(30) NOT NULL,
    recorded_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gearbox_temp DECIMAL(6, 2) NOT NULL,
    blade_vibration DECIMAL(6, 2) NOT NULL,
    yaw_misalignment DECIMAL(6, 2) DEFAULT 0.00,
    sand_dust_wear DECIMAL(6, 2) DEFAULT 0.00,
    ice_accumulation DECIMAL(6, 2) DEFAULT 0.00,
    rotor_speed DECIMAL(6, 2) NOT NULL,
    actual_energy_mwh DECIMAL(8, 2) NOT NULL,
    operating_hours DECIMAL(6, 2) NOT NULL,
    scada_error_code VARCHAR(100) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_telemetry PRIMARY KEY (telemetry_id),
    CONSTRAINT fk_telemetry_turbine FOREIGN KEY (turbine_id)
        REFERENCES turbines (turbine_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    INDEX idx_telemetry_turbine_time (turbine_id, recorded_timestamp)
) ENGINE=InnoDB;

-- -----------------------------------------------------------------------------
-- 3. MAINTENANCE_TICKETS TABLE: Predictive work orders generated by health bands
-- -----------------------------------------------------------------------------
CREATE TABLE maintenance_tickets (
    ticket_id VARCHAR(40) NOT NULL,
    turbine_id VARCHAR(30) NOT NULL,
    category VARCHAR(50) NOT NULL,
    health_score DECIMAL(5, 2) NOT NULL,
    health_band VARCHAR(100) NOT NULL,
    brake_lock_triggered BOOLEAN NOT NULL DEFAULT FALSE,
    capacity_factor DECIMAL(5, 2) NOT NULL,
    recommended_action TEXT NOT NULL,
    urgency_level VARCHAR(20) NOT NULL,
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_tickets PRIMARY KEY (ticket_id),
    CONSTRAINT fk_tickets_turbine FOREIGN KEY (turbine_id)
        REFERENCES turbines (turbine_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    INDEX idx_tickets_turbine (turbine_id),
    INDEX idx_tickets_band (health_band)
) ENGINE=InnoDB;

-- -----------------------------------------------------------------------------
-- 4. DOWNTIME_LOGS TABLE: Operational lockout logs for tripped/offline assets
-- -----------------------------------------------------------------------------
CREATE TABLE downtime_logs (
    downtime_id BIGINT AUTO_INCREMENT NOT NULL,
    turbine_id VARCHAR(30) NOT NULL,
    incident_reason VARCHAR(255) NOT NULL,
    root_cause_metric VARCHAR(100) NOT NULL,
    metric_value DECIMAL(8, 2) NOT NULL,
    threshold_exceeded DECIMAL(8, 2) NOT NULL,
    lockout_status VARCHAR(50) NOT NULL,
    logged_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_downtime PRIMARY KEY (downtime_id),
    CONSTRAINT fk_downtime_turbine FOREIGN KEY (turbine_id)
        REFERENCES turbines (turbine_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    INDEX idx_downtime_turbine (turbine_id),
    INDEX idx_downtime_logged (logged_at)
) ENGINE=InnoDB;

